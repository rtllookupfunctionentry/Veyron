#!/bin/sh
# hk_symbols.sh OUT.c OBJ...: the table of every global C symbol (function or constant) the objects define, for
# hk_lookup. Objective-C metadata and Henge's own hk_ names are left out. Names are bound with asm labels, so the
# table needs no prototypes.
out=$1; shift
# Classes too (_OBJC_CLASS_$_X, _OBJC_METACLASS_$_X): iOS has its own classes named NSColor and NSFont, so a class
# is looked up as this image's symbol, never by name.
nm -gUj "$@" 2>/dev/null | grep -E '^_{1,2}[A-Za-z][A-Za-z0-9_]*$|^_OBJC_(META)?CLASS_\$_[A-Za-z_][A-Za-z0-9_]*$' | grep -v '^_hk_' | sort -u > "$out.names"
{
    echo "/* Generated by tl/shim/tools/hk_symbols.sh: do not edit. */"
    echo "typedef struct { const char *name; void *address; } HKSymbol;"
    i=0
    while read -r sym; do echo "extern char hk_s$i __asm(\"$sym\");"; i=$((i + 1)); done < "$out.names"
    echo "const HKSymbol hk_symbols[] = {"
    i=0
    while read -r sym; do echo "    {\"$sym\", &hk_s$i},"; i=$((i + 1)); done < "$out.names"
    echo "    {0, 0}};"
    echo "const int hk_nsymbols = $i;"
} > "$out"
rm -f "$out.names"
